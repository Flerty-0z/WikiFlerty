package com.flerty.wikiflerty.ai

enum class AiAction(val id: String, val title: String, val hint: String, val mark: String, val forSelection: Boolean = true) {
    Explain("explain", "Объяснить", "Просто, с учётом текста вокруг", "?"),
    Define("define", "Определение", "Как в толковом словаре", "Аб"),
    Translate("translate", "Перевод", "На выбранный язык", "En"),
    Ask("ask", "Свой вопрос", "Что угодно об отрывке", "…"),
    Debate("debate", "Спор с автором", "Контраргументы к этой мысли", "⇄"),
    Recap("recap", "Пересказ главы", "Что было до этого места", "≡", forSelection = false),
    Quiz("quiz", "Тест по главе", "5 вопросов на понимание", "✓", forSelection = false),
}

object AiPrompts {
    fun system(bookTitle: String, author: String, settings: AiSettings): String = buildString {
        append("Ты — умный помощник внутри читалки электронных книг. ")
        append("Пользователь читает книгу «$bookTitle»")
        if (author.isNotBlank()) append(" ($author)")
        append(". Отвечай по-русски, понятно и доходчиво, как хороший учитель, без воды и без вступлений вроде «Конечно!». ")
        if (settings.style == "detailed") {
            append("Давай развёрнутые ответы с примерами. ")
        } else {
            append("Отвечай коротко: обычно 2–5 предложений. ")
        }
        append("Можно использовать **жирный** для ключевых слов и короткие списки через «- ». Не используй таблицы и заголовки.")
    }

    fun first(action: AiAction, selected: String, context: String, settings: AiSettings, question: String? = null): String {
        val fragment = selected.trim()
        val around = context.trim().takeIf { it.isNotEmpty() && it != fragment }
        val contextLine = around?.let { "\n\nКонтекст из книги: «$it»" }.orEmpty()
        return when (action) {
            AiAction.Explain ->
                "Объясни простыми словами, что значит «$fragment» в этом месте книги. " +
                    "Сначала смысл именно здесь, потом коротко общее значение, если оно отличается.$contextLine"
            AiAction.Define ->
                "Дай словарное определение для «$fragment»: часть речи, основное значение " +
                    "(и другие, если важны), короткий пример употребления. Отметь, какое значение использовано в книге.$contextLine"
            AiAction.Translate ->
                "Переведи «$fragment» на ${language(settings)}. Переводи живо и естественно, как хороший литературный " +
                    "переводчик: передай смысл, тон и стиль автора, а не слова по отдельности; соблюдай грамматику и привычный " +
                    "порядок слов этого языка. Если это отдельное слово или устойчивое выражение — дай 2–3 варианта с коротким " +
                    "пояснением оттенков и отметь, какой подходит именно здесь. Если это фраза или абзац — дай один цельный " +
                    "перевод без пояснений.$contextLine"
            AiAction.Ask ->
                "Вопрос об отрывке «$fragment»: ${question.orEmpty().trim()}$contextLine"
            AiAction.Debate ->
                "Поспорь с автором по поводу мысли «$fragment». Найди самые сильные контраргументы — честно и по делу, " +
                    "опираясь на логику, жизненный опыт и исследования, если они есть. Не соглашайся с автором и не смягчай. " +
                    "Ответь строго в таком формате, без вступлений и заключений:\n" +
                    "Автор прав не во всём:\n" +
                    "1. первый контраргумент в 1–2 предложениях\n" +
                    "2. второй контраргумент\n" +
                    "3. третий контраргумент\n" +
                    "Вопрос тебе: один вопрос, который заставит меня задуматься и продолжить спор.$contextLine"
            AiAction.Recap ->
                "Кратко перескажи, что происходит в главе «$fragment» до того места, где я сейчас читаю. " +
                    "По порядку, 6–10 предложений: ключевые события, мысли и выводы автора. Опирайся только на этот текст, " +
                    "ничего не придумывай и не забегай вперёд.\n\nТекст главы до текущего места:\n«${context.trim()}»"
            AiAction.Quiz ->
                "Составь короткий тест на понимание главы «$fragment» — 5 вопросов только по прочитанному тексту ниже. " +
                    "У каждого вопроса 3 варианта ответа: А, Б, В. Правильные ответы НЕ показывай. В конце попроси меня " +
                    "ответить одной строкой, например «1А 2В 3Б 4А 5Б». Когда я отвечу — проверь, скажи результат и коротко " +
                    "объясни ошибки со ссылкой на текст.\n\nТекст главы до текущего места:\n«${context.trim()}»"
        }
    }

    private fun language(settings: AiSettings): String {
        val name = settings.translateTo.trim()
        return if (name.endsWith("ий") || name.endsWith("ый")) "$name язык" else name
    }

    fun followUps(settings: AiSettings, action: AiAction): List<Pair<String, String>> = when (action) {
        AiAction.Recap -> listOf(
            "Короче" to "Перескажи ещё короче — в 3 предложениях.",
            "Главная мысль" to "Какая главная мысль этой части главы?",
            "Персонажи" to "Кто здесь действует и что о них важно знать?",
        )
        AiAction.Quiz -> listOf(
            "Ответы" to "Покажи правильные ответы с коротким пояснением.",
            "Ещё тест" to "Сделай ещё 5 других вопросов по этому же тексту.",
            "Сложнее" to "Сделай 5 вопросов посложнее, на детали и смысл.",
        )
        AiAction.Debate -> listOf(
            "Согласен с автором" to "Я всё-таки согласен с автором. Приведи самый сильный аргумент в его защиту, а потом " +
                "найди в нём слабое место. В конце отдельной строкой: «Вопрос тебе: …».",
            "Возразить" to "Твои аргументы меня не до конца убедили. Возьми самый сильный из них и представь, как автор " +
                "ответил бы на него. Затем скажи, кто, по-твоему, прав. В конце отдельной строкой: «Вопрос тебе: …».",
            "Ещё аргумент" to "Приведи ещё один, более неожиданный контраргумент. Формат: одна пронумерованная строка, " +
                "продолжающая нумерацию, затем отдельной строкой «Вопрос тебе: …».",
        )
        else -> selectionFollowUps(settings)
    }

    fun hero(name: String, role: String, bookTitle: String, author: String, isAuthor: Boolean, noSpoilers: Boolean, text: String): String = buildString {
        if (isAuthor) {
            append("Ты — $name, автор книги «$bookTitle». Говори от первого лица как этот автор: его взгляды, эпоха, ")
            append("манера речи и характер. Рассказывай о замысле, героях и идеях книги так, как это сделал бы он сам. ")
        } else {
            append("Ты — $name")
            if (role.isNotBlank()) append(" ($role)")
            append(", персонаж книги «$bookTitle»")
            if (author.isNotBlank()) append(" ($author)")
            append(". Отвечай от первого лица, в характере, манере и лексике этого героя — так, как он говорит в книге. ")
        }
        append("Никогда не выходи из роли и не упоминай, что ты ИИ или языковая модель. Отвечай живо и по-человечески, ")
        append("обычно 2–6 предложений, по-русски. Можно изредка описать жест или действие курсивом, например *вздыхает*. ")
        append("Не используй списки, заголовки и таблицы. ")
        if (noSpoilers) {
            append("Важно: ты знаешь только то, что произошло в тексте ниже — это всё, что собеседник уже прочитал. ")
            append("Не упоминай и не намекай на события, которых в этом тексте нет. Если спрашивают о будущем — ")
            append("ответь в образе, что не знаешь, чем всё обернётся. ")
        } else {
            append("Можешь опираться на всё, что знаешь об этой книге целиком. ")
        }
        if (text.isNotBlank()) {
            append("\n\nТекст книги, прочитанный собеседником (фрагменты):\n«")
            append(text)
            append("»")
        }
    }

    fun heroesPrompt(text: String): String =
        "Ниже текст книги, который я уже прочитал. Найди в нём до 8 самых важных персонажей, которые действительно появляются " +
            "в этом тексте (не упоминай тех, кого в тексте нет). Для каждого дай короткое описание роли — 2–5 слов, без спойлеров. " +
            "Ответь ТОЛЬКО JSON-массивом без пояснений, например: " +
            "[{\"name\": \"Имя Фамилия\", \"role\": \"главный герой, студент\"}]\n\nТекст:\n«$text»"

    private fun selectionFollowUps(settings: AiSettings) = listOf(
        "Проще" to "Объясни ещё проще, как для школьника.",
        "Примеры" to "Приведи 2–3 коротких примера употребления.",
        "Синонимы" to "Какие есть синонимы и чем они отличаются по оттенку?",
        "Перевод" to "Переведи этот отрывок на ${language(settings)} — естественно, литературно, с сохранением стиля автора.",
    )
}
